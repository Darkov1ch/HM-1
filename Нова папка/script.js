document.addEventListener("DOMContentLoaded", () => {
  const book = document.querySelector(".book");
  const pageContent = document.getElementById("page-content");
  const leftArea = document.querySelector(".click-area.left");
  const rightArea = document.querySelector(".click-area.right");

  const pages = [
    "Накрийте на стіл: Чітке визначення цілей – перший крок до успіху. Записуйте свої цілі на папері та встановлюйте дедлайни. Дедлайни вже встановлені GoIT тому просто слідуйте визначеному маршруту і пам'ятайте студенти які вчаться 14 годин в тиждень точно знаходять роботу.",
    "Заздалегідь плануйте кожен день: Планування економить час. Складіть список завдань на день, тиждень і місяць, пріоритезуйте їх. Обов'язково зробіть це на папері ви отримаєте  велике задоволення викреслюючи виконані цілі.",
    "Правило 80/20: 20% зусиль дають 80% результатів. Зосередьтеся на найважливіших завданнях. Ідеальне - ворог доброго. ",
    "Думайте про наслідки: Оцінюйте довгострокові наслідки своїх дій. Обирайте ті завдання, які мають найбільший вплив на ваше майбутнє. Опануйте техніку Bebi steps. Маленькі кроки приведуть Вас до великих звершень!",
    "Займайтесь творчою прокрастинацією: Усвідомлено відмовляйтеся від малозначущих завдань, щоб зосередитися на ключових. Хваліть себе за кожну відмову від короткочасного завдоволення заради ще одного кроку до мети!",
    "Використовуйте закон примусової ефективності: Часу на все не вистачить, тому завжди виконуйте найважливіші справи першими. Справва в пріоритеті, спитайте себе (що для мене справді важливо?)",
    "Підвищуйте власну компетентність: Постійне навчання та розвиток підвищують продуктивність. Пам'ятайте що навіть 30 хвилин денеь в новій справі зроблять Вас кращими зя 90% інших людей",
    "Розбийте слона на шматочки: Великі завдання виконуйте поступово, розбивши їх на дрібні етапи. Спочатку Ви повзали, потім ходили, а вже потім бігли. Завжди найтяжче - почати!",
    "Мотивуйте себе на дію: Позитивне мислення та внутрішня мотивація допомагають долати прокрастинацію.Ви завжди зможете знайти підтримку у нашому колі однодумців(GoIT) та в собі.",
    "Якщо Ваш внутрішній голос це Ви, то хто ж тоді слухає?",
  ];

  let currentPage = 0;

  function showPage(index) {
    const parts = pages[index].split(": ");
    pageContent.innerHTML = `<h1>${parts[0]}</h1><p>${parts[1] || ""}</p>`;
  }


  book.addEventListener("click", () => {
    book.classList.add("open");
    showPage(currentPage);
  });

  rightArea.addEventListener("click", (event) => {
    event.stopPropagation(); // Запобігаємо конфлікту з кліком на книгу
    if (currentPage < pages.length - 1) {
      currentPage++;
      showPage(currentPage);
    }
  });

  leftArea.addEventListener("click", (event) => {
    event.stopPropagation();
    if (currentPage > 0) {
      currentPage--;
      showPage(currentPage);
    }
  });
});
